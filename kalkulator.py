# Input
angka1 = int(input("Angka 1: "))
angka2 = int(input("Angka 2: "))

# Proses dan Output
print(f"{angka1} + {angka2} = {angka1 + angka2}")
print(f"{angka1} - {angka2} = {angka1 - angka2}")
print(f"{angka1} * {angka2} = {angka1 * angka2}")
print(f"{angka1} / {angka2} = {angka1 / angka2}")
print(f"{angka1} // {angka2} = {angka1 // angka2}")
print(f"{angka1} % {angka2} = {angka1 % angka2}")
print(f"{angka1} ** {angka2} = {angka1 ** angka2}")
